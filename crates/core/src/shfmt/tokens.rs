pub fn quote(s: &str) -> String {
    let backquotable = s
        .chars()
        .all(|c| c != '`' && c != '\u{FEFF}' && (c >= ' ' || c == '\t') && c != '\u{7F}');
    if backquotable {
        return format!("`{s}`");
    }
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            '\u{7}' => out.push_str("\\a"),
            '\u{8}' => out.push_str("\\b"),
            '\u{C}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{B}' => out.push_str("\\v"),
            c if c < ' ' || c == '\u{7F}' => out.push_str(&format!("\\x{:02x}", c as u32)),
            c if c.is_control() || c == '\u{FEFF}' => {
                if (c as u32) < 0x10000 {
                    out.push_str(&format!("\\u{:04x}", c as u32));
                } else {
                    out.push_str(&format!("\\U{:08x}", c as u32));
                }
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
